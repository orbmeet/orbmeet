"""Regenerate src/modules/billing/server/country-currencies.ts.

Polar's checkout picks a currency from the buyer's country: the first of the
country's current currencies (per the `babel` library) that Polar supports,
else the organization's default. This writes that mapping for every country so
the app can show the price checkout will charge.

    python3 -m venv /tmp/cc && /tmp/cc/bin/pip install "babel==<Polar's version>"
    /tmp/cc/bin/python -I scripts/country-currencies.py <polar>/server/polar/kit/currency.py \\
        > src/modules/billing/server/country-currencies.ts

Use the babel version pinned in Polar's server/uv.lock, and Polar's
kit/currency.py for the currencies it supports (its PresentmentCurrency enum).
"""

import ast
import sys

import babel
from babel.core import get_global
from babel.numbers import get_territory_currencies

source = open(sys.argv[1], encoding="utf-8").read()
enum = next(
    node for node in ast.parse(source).body
    if isinstance(node, ast.ClassDef) and node.name == "PresentmentCurrency"
)
supported = {
    stmt.value.value for stmt in enum.body
    if isinstance(stmt, ast.Assign) and isinstance(stmt.value, ast.Constant)
}

table: dict[str, str] = {}
for territory in sorted(get_global("territory_currencies")):
    if len(territory) != 2 or not territory.isalpha():
        continue
    for currency in get_territory_currencies(territory):
        if currency.lower() in supported:
            table[territory] = currency.lower()
            break

entries = [f'{country}: "{currency}"' for country, currency in table.items()]
lines = [", ".join(entries[i:i + 8]) + "," for i in range(0, len(entries), 8)]
print(f"""// Generated by apps/web/scripts/country-currencies.py (babel {babel.__version__}); do not edit.
//
// The currency Polar's checkout charges in each country, before falling back
// to the organization's default: the first of the country's current currencies
// that Polar supports. Countries absent here (e.g. Bulgaria, still BGN in this
// babel) always get the default. Regenerate when Polar updates babel.
export const COUNTRY_CURRENCIES: Readonly<Record<string, string>> = {{""")
for line in lines:
    print(f"  {line}")
print("};")
